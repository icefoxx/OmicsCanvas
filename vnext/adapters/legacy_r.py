"""Adapter between validated PlotSpecs and the legacy R plugins' flat params.json.

Both directions are driven by plugins/<id>/vnext/metadata.yaml (generated by
``python -m vnext.cli migrate``), so every migrated skill shares one adapter:

  PlotSpec.mapping      role -> column   <->  metadata.roles[role].param
  PlotSpec.statistics   field -> value   <->  metadata.statistics[field]
  PlotSpec.export       width/height/dpi <->  width / height / dpi
  PlotSpec.visual       curated fields   ->   metadata.visual (aliases) or same name
  PlotSpec.legacy_params                 <->  every other plugin parameter

``legacy_params_to_plotspec`` followed by ``plotspec_to_legacy_params`` is
lossless for any params.json (tested over every example bundle).
The adapter maps fields only; it never invents scientific choices.
"""
from __future__ import annotations

import copy
import json
import shutil
import subprocess
from pathlib import Path
from typing import Any, Callable

import yaml

ROOT = Path(__file__).resolve().parents[2]
PLUGIN_DIR = ROOT / "plugins"

# Run-control keys plot_web adds to params.json; not part of the figure semantics.
RUN_CONTROL_KEYS = {"plugin_id", "dispatch_mode"}
STATISTICS_LIST_FIELDS = {"comparisons"}

_META_CACHE: dict[Path, tuple[float, dict[str, Any]]] = {}


def load_skill_metadata(skill_id: str) -> dict[str, Any] | None:
    path = PLUGIN_DIR / str(skill_id) / "vnext" / "metadata.yaml"
    try:
        mtime = path.stat().st_mtime
    except OSError:
        return None
    hit = _META_CACHE.get(path)
    if hit is None or hit[0] != mtime:
        data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
        _META_CACHE[path] = (mtime, data if isinstance(data, dict) else {})
    return copy.deepcopy(_META_CACHE[path][1])


def role_params(meta: dict[str, Any]) -> dict[str, str]:
    """role -> plugin parameter (including role aliases)."""
    out = {role: str(entry["param"]) for role, entry in (meta.get("roles") or {}).items() if entry.get("param")}
    for alias, role in (meta.get("role_aliases") or {}).items():
        if role in out:
            out.setdefault(alias, out[role])
    return out


def unsupported_roles(spec: dict[str, Any], meta: dict[str, Any] | None) -> list[str]:
    """Mapped roles the skill's renderer has no parameter for (they would be silently dropped)."""
    if not meta:
        return []
    known = role_params(meta)
    return [role for role, col in (spec.get("mapping") or {}).items() if col not in (None, "", []) and role not in known]


def _sort_params_hook(spec: dict[str, Any], params: dict[str, Any]) -> None:
    """Declarative PlotSpec.transform -> sort/top_n parameters (enrichment lollipop)."""
    transform = spec.get("transform") or {}
    ranking = transform.get("ranking") or {}
    if ranking.get("field"):
        params.setdefault("sort_by", "value")
        method = ranking.get("method") or "desc"
        params["sort"] = "ascending" if method in {"asc", "abs_asc"} else "descending"
    if transform.get("top_n"):
        params["top_n"] = transform["top_n"]
    if transform.get("preserve_order"):
        params["sort"] = "none"


TRANSFORM_HOOKS: dict[str, Callable[[dict[str, Any], dict[str, Any]], None]] = {
    "sort_params": _sort_params_hook,
}


def plotspec_to_legacy_params(spec: dict[str, Any], meta: dict[str, Any] | None = None) -> dict[str, Any]:
    """PlotSpec -> flat params.json for the skill's R plugin."""
    skill_id = (spec.get("skill") or {}).get("id") or ""
    meta = meta if meta is not None else (load_skill_metadata(skill_id) or {})
    params: dict[str, Any] = copy.deepcopy(spec.get("legacy_params") or {})

    roles = role_params(meta)
    for role, col in (spec.get("mapping") or {}).items():
        if role in roles:
            params[roles[role]] = copy.deepcopy(col)

    for field, param in (meta.get("statistics") or {}).items():
        value = (spec.get("statistics") or {}).get(field)
        if value is not None:
            params[param] = copy.deepcopy(value)

    visual_map = meta.get("visual") or {}
    for key, value in (spec.get("visual") or {}).items():
        target = visual_map.get(key, key) if key in visual_map else key
        if target is None or value is None:
            continue
        params[target] = bool(value) if key in {"zero_line", "stem_to_zero"} else copy.deepcopy(value)

    hook = TRANSFORM_HOOKS.get(str(meta.get("transform_hook") or ""))
    if hook:
        hook(spec, params)

    export = spec.get("export") or {}
    if export.get("width_in") is not None:
        params["width"] = export["width_in"]
    elif export.get("width_mm") is not None:
        params["width"] = float(export["width_mm"]) / 25.4
    if export.get("height_in") is not None:
        params["height"] = export["height_in"]
    elif export.get("height_mm") is not None:
        params["height"] = float(export["height_mm"]) / 25.4
    if export.get("dpi") is not None:
        params["dpi"] = export["dpi"]

    params["plugin_id"] = skill_id
    return params


def _is_mapping_value(value: Any) -> bool:
    return value is None or isinstance(value, str) or (isinstance(value, list) and all(isinstance(v, str) for v in value))


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def legacy_params_to_plotspec(
    skill_id: str,
    params: dict[str, Any],
    *,
    meta: dict[str, Any] | None = None,
    inputs: dict[str, dict[str, Any]] | None = None,
    seed: int | None = None,
) -> dict[str, Any]:
    """Flat params.json -> PlotSpec (inverse of plotspec_to_legacy_params)."""
    from vnext.plotspec.model import empty_spec

    meta = meta if meta is not None else (load_skill_metadata(skill_id) or {})
    spec = empty_spec(skill_id, str(meta.get("version") or "1.0.0"))
    rest = {k: copy.deepcopy(v) for k, v in params.items() if k not in RUN_CONTROL_KEYS}

    for role, entry in (meta.get("roles") or {}).items():
        param = entry.get("param")
        if param in rest and _is_mapping_value(rest[param]):
            spec["mapping"][role] = rest.pop(param)

    stats = spec["statistics"]
    for field, param in (meta.get("statistics") or {}).items():
        if param not in rest:
            continue
        value = rest[param]
        ok = value is None or isinstance(value, str) or (field in STATISTICS_LIST_FIELDS and isinstance(value, list))
        if ok:
            stats[field] = rest.pop(param)

    export = spec["export"]
    if _is_number(rest.get("width")) and rest["width"] >= 0.5:
        export["width_in"] = rest.pop("width")
    if _is_number(rest.get("height")) and rest["height"] >= 0.5:
        export["height_in"] = rest.pop("height")
    dpi = rest.get("dpi")
    if _is_number(dpi) and float(dpi).is_integer() and 72 <= dpi <= 1200:
        export["dpi"] = int(rest.pop("dpi"))
    else:
        export.pop("dpi", None)

    spec["legacy_params"] = rest
    if inputs:
        spec["inputs"] = copy.deepcopy(inputs)
        main = inputs.get("input") or inputs.get("file") or next(iter(inputs.values()))
        spec["input"] = {k: main[k] for k in ("source_file", "checksum", "format") if k in main}
    if seed is not None:
        spec["provenance"]["seed"] = int(seed)
    return spec


def run_legacy_plugin(
    *,
    skill_id: str,
    params: dict[str, Any],
    output_dir: Path,
    input_path: Path | None = None,
    inputs: dict[str, Path] | None = None,
    seed: int | None = None,
    timeout: int = 600,
) -> dict[str, Any]:
    """Render with the plugin exactly as plot_web would (same CLI flags, seeded R env)."""
    from plot_web.server.runner import DEFAULT_SEED, build_command, plugin_env
    from plot_web.app import read_yaml

    plugin = PLUGIN_DIR / skill_id
    if not (plugin / "plot.R").exists():
        raise FileNotFoundError(f"Missing renderer: {plugin / 'plot.R'}")
    files = {k: Path(v).resolve() for k, v in (inputs or {}).items()}
    if input_path is not None:
        files.setdefault("input", Path(input_path).resolve())
    output_dir = Path(output_dir).resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    params_path = output_dir / "params.json"
    params_path.write_text(json.dumps(params, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    for path in files.values():
        copy_to = output_dir / path.name
        if path != copy_to and not copy_to.exists():
            shutil.copy2(path, copy_to)

    config = read_yaml(plugin / "config.yaml")
    cmd = build_command(skill_id, config, files, params_path, output_dir)
    proc = subprocess.run(cmd, cwd=str(ROOT), capture_output=True, text=True, timeout=timeout,
                          env=plugin_env(DEFAULT_SEED if seed is None else seed))
    (output_dir / "adapter_stdout.log").write_text(proc.stdout or "", encoding="utf-8")
    (output_dir / "adapter_stderr.log").write_text(proc.stderr or "", encoding="utf-8")
    figures = {}
    for name, key in [("result.svg", "svg"), ("result.pdf", "pdf"), ("result.png", "png"),
                      ("result.html", "html"), ("figure.json", "figure_json"), ("run.log", "log")]:
        if (output_dir / name).exists():
            figures[key] = output_dir / name
    return {
        "returncode": proc.returncode,
        "ok": proc.returncode == 0 and ("svg" in figures or "png" in figures),
        "command": cmd,
        "figures": {k: str(v) for k, v in figures.items()},
        "figure_paths": figures,
        "params_path": str(params_path),
    }
